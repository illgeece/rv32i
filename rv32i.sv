         assign CPU_mcycleh_old_a2[31:0] = CPU_mcycleh_a3;
         assign CPU_minstret_old_a2[31:0] = CPU_minstret_a3;
         assign CPU_minstreth_old_a2[31:0] = CPU_minstreth_a3;
         assign CPU_mtvec_old_a2[31:0] = CPU_mtvec_a3;
         assign CPU_mepc_old_a2[31:0] = CPU_mepc_a3;
         assign CPU_mcause_old_a2[31:0] = CPU_mcause_a3;
         assign CPU_mtval_old_a2[31:0] = CPU_mtval_a3;
         assign CPU_mstatus_mpie_old_a2 = CPU_mstatus_mpie_a3;
         assign CPU_mstatus_mie_old_a2 = CPU_mstatus_mie_a3;
           //mstatus_value for an M mode only processor only has 2 variable flops
         assign CPU_mstatus_value_a2[31:0] = {19'b0, 2'b11, 3'b0, CPU_mstatus_mpie_old_a2, 3'b0, CPU_mstatus_mie_old_a2, 3'b0};
         assign CPU_trap_target_pc_a2[31:0] = CPU_mtvec_old_a2;
         assign CPU_mret_target_pc_a2[31:0] = CPU_mepc_old_a2;
           //misa register fields, editable for future extension
         assign CPU_misa_mxl_a2[1:0] = 2'b01; //rv32
         assign CPU_misa_extensions_a2[25:0] = 26'h100; //I mode
         assign CPU_misa_val_a2[31:0] = {CPU_misa_mxl_a2, 4'b0, CPU_misa_extensions_a2};
           //read-mod-write muxes
         assign CPU_csr_read_data_a2[31:0] = (CPU_csr_addr_a2 == 12'h300) ? CPU_mstatus_value_a2:
                                (CPU_csr_addr_a2 == 12'h340) ? CPU_mscratch_old_a2:
                                (CPU_csr_addr_a2 == 12'h301) ? CPU_misa_val_a2:
                                (CPU_csr_addr_a2 == 12'h305) ? CPU_mtvec_old_a2:
                                (CPU_csr_addr_a2 == 12'h341) ? CPU_mepc_old_a2:
                                (CPU_csr_addr_a2 == 12'h342) ? CPU_mcause_old_a2:
                                (CPU_csr_addr_a2 == 12'h343) ? CPU_mtval_old_a2:
                                (CPU_csr_addr_a2 == 12'hB00) ? CPU_mcycle_old_a2:
                                (CPU_csr_addr_a2 == 12'hB02) ? CPU_minstret_old_a2:
                                (CPU_csr_addr_a2 == 12'hB80) ? CPU_mcycleh_old_a2:
                                (CPU_csr_addr_a2 == 12'hB82) ? CPU_minstreth_old_a2:
                                32'b0; //more CSRs go here, also covers mstatush and all four 0xF1x regs
         assign CPU_csr_src_a2[31:0] = CPU_is_csr_imm_a2 ? CPU_csr_uimm_a2 : CPU_src1_value_fwd_a2;
         assign CPU_csr_new_value_a2[31:0] = (CPU_is_csrrw_a2 || CPU_is_csrrwi_a2) ? CPU_csr_src_a2:
                              (CPU_is_csrrs_a2 || CPU_is_csrrsi_a2) ? CPU_csr_read_data_a2 | CPU_csr_src_a2:
                              (CPU_is_csrrc_a2 || CPU_is_csrrci_a2) ? CPU_csr_read_data_a2 & ~CPU_csr_src_a2:
                              32'b0;
         assign CPU_csr_wr_en_a2 = CPU_csr_wr_req_a2 && CPU_retires_a2;
           //trap payload and entry, moves complexity from next block
         assign CPU_exception_cause_a2[31:0] = CPU_valid_trap_a2 ? CPU_trap_cause_a2:
                                  (CPU_valid_misaligned_id_a2 || CPU_valid_misaligned_ex_a2) ? 32'd0:
                                  CPU_valid_misaligned_mem_a2 ? (CPU_is_store_a2 ? 32'd6 : 32'd4):
                                  32'hFFFFFFFF;
         assign CPU_exception_tvalue_a2[31:0] = CPU_valid_trap_a2 ? (CPU_is_ebreak_a2 ? CPU_pc_a2 : 32'b0): //breakpoint reports the faulting address; ecall and illegal-instr report 0
                                   CPU_valid_misaligned_id_a2 ? CPU_br_target_pc_a2:
                                   CPU_valid_misaligned_ex_a2 ? (CPU_is_jalr_a2 ? CPU_jalr_target_pc_a2 : CPU_br_target_pc_a2):
                                   CPU_valid_misaligned_mem_a2 ? CPU_addr_a2:
                                   32'hFFFFFFFF;
           //next state flops
             //write and carry signals
         assign CPU_mcycle_wr_a2 = CPU_csr_wr_en_a2 && CPU_csr_addr_a2 == 12'hB00;
         assign CPU_mcycleh_wr_a2 = CPU_csr_wr_en_a2 && CPU_csr_addr_a2 == 12'hB80;
         assign CPU_minstret_wr_a2 = CPU_csr_wr_en_a2 && CPU_csr_addr_a2 == 12'hB02;
         assign CPU_minstreth_wr_a2 = CPU_csr_wr_en_a2 && CPU_csr_addr_a2 == 12'hB82;
         assign CPU_mcycle_carry_a2 = !CPU_mcycle_wr_a2 && (CPU_mcycle_old_a2 == 32'hFFFFFFFF);
         assign CPU_minstret_carry_a2 = CPU_retires_a2 && !CPU_minstret_wr_a2 && (CPU_minstret_old_a2 == 32'hFFFFFFFF);
             //actual flops
         assign CPU_mscratch_a2[31:0] = CPU_reset_a2 ? 32'b0:  //plain storage: hold unless written
                           (CPU_csr_wr_en_a2 && CPU_csr_addr_a2 == 12'h340) ? CPU_csr_new_value_a2 : CPU_mscratch_old_a2;
         assign CPU_mcycle_a2[31:0] = CPU_reset_a2 ? 32'b0:    //background update, counts unless there is an explicit write
                         CPU_mcycle_wr_a2 ? CPU_csr_new_value_a2 : (CPU_mcycle_old_a2 + 32'b1);
         assign CPU_mcycleh_a2[31:0] = CPU_reset_a2 ? 32'b0: //upper regs for the 64 bit counters mcycleh and minstreth
                           CPU_mcycleh_wr_a2 ? CPU_csr_new_value_a2:
                           CPU_mcycleh_old_a2 + {31'b0, CPU_mcycle_carry_a2};
         assign CPU_minstret_a2[31:0] = CPU_reset_a2 ? 32'b0:  //counts retirements not cycles, only adds one if valid and not explicit write
                           CPU_minstret_wr_a2 ? CPU_csr_new_value_a2: CPU_minstret_old_a2 + {31'b0, CPU_retires_a2};
         assign CPU_minstreth_a2[31:0] = CPU_reset_a2 ? 32'b0:
                            CPU_minstreth_wr_a2 ? CPU_csr_new_value_a2:
                            CPU_minstreth_old_a2 + {31'b0, CPU_minstret_carry_a2};
         assign CPU_mtvec_a2[31:0] = CPU_reset_a2 ? 32'b0:
                        (CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h305)) ? {CPU_csr_new_value_a2[31:2], 2'b00}: //mask to set MODE to direct
                        CPU_mtvec_old_a2;
         assign CPU_mepc_a2[31:0] = CPU_reset_a2 ? 32'b0:
                       CPU_take_trap_a2 ? CPU_pc_a2:
                       (CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h341)) ? {CPU_csr_new_value_a2[31:2], 2'b00}: //masks low bits to align, will change with C extension
                       CPU_mepc_old_a2;
         assign CPU_mcause_a2[31:0] = CPU_reset_a2 ? 32'b0: //32b sig to match RISCOF test result over spec matching
                         CPU_take_trap_a2 ? CPU_exception_cause_a2:
                         (CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h342)) ? CPU_csr_new_value_a2:
                         CPU_mcause_old_a2;
         assign CPU_mtval_a2[31:0] = CPU_reset_a2 ? 32'b0:
                        CPU_take_trap_a2 ? CPU_exception_tvalue_a2:
                        CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h343) ? CPU_csr_new_value_a2: //mutually exclusive w above
                        CPU_mtval_old_a2;
         assign CPU_mstatus_mie_a2 = CPU_reset_a2 ? 1'b0: //interrupts currently enabled
                        CPU_take_trap_a2 ? 1'b0:
                        CPU_valid_mret_a2 ? CPU_mstatus_mpie_old_a2:
                        (CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h300)) ? CPU_csr_new_value_a2[3] : CPU_mstatus_mie_old_a2;
         assign CPU_mstatus_mpie_a2 = CPU_reset_a2 ? 1'b0: //interrupts enabled before trap
                         CPU_take_trap_a2 ? CPU_mstatus_mie_old_a2:
                         CPU_valid_mret_a2 ? 1'b1:
                         (CPU_csr_wr_en_a2 && (CPU_csr_addr_a2 == 12'h300)) ? CPU_csr_new_value_a2[7] : CPU_mstatus_mpie_old_a2;

         //Branch Logic
         assign CPU_src2_or_imm_fwd_a2[31:0] = CPU_is_r_instr_a2 ? CPU_src2_value_fwd_a2 : CPU_imm_a2;
         assign CPU_taken_br_a2 = CPU_is_b_instr_a2 && CPU_is_beq_a2 ? CPU_src1_value_fwd_a2 == CPU_src2_value_fwd_a2:
                     CPU_is_b_instr_a2 && CPU_is_bne_a2 ? CPU_src1_value_fwd_a2 != CPU_src2_value_fwd_a2:
                     CPU_is_b_instr_a2 && CPU_is_blt_a2 ? (CPU_src1_value_fwd_a2 < CPU_src2_value_fwd_a2) ^ (CPU_src1_value_fwd_a2[31] != CPU_src2_value_fwd_a2[31]):
                     CPU_is_b_instr_a2 && CPU_is_bge_a2 ? (CPU_src1_value_fwd_a2 >= CPU_src2_value_fwd_a2) ^ (CPU_src1_value_fwd_a2[31] != CPU_src2_value_fwd_a2[31]):
                     CPU_is_b_instr_a2 && CPU_is_bltu_a2 ? CPU_src1_value_fwd_a2 < CPU_src2_value_fwd_a2:
                     CPU_is_b_instr_a2 && CPU_is_bgeu_a2 ? CPU_src1_value_fwd_a2 >= CPU_src2_value_fwd_a2:
                     1'b0;
           //misprediction logic
         assign CPU_mispredicted_a2 = !(CPU_is_jal_a2 || CPU_is_jalr_a2 || CPU_is_mret_a2) //these instructions self correct earlier in the pipeline
                         && ((CPU_taken_br_a2 != CPU_pred_taken_f_a2) || (CPU_taken_br_a2 && CPU_pred_taken_f_a2 && (CPU_br_target_pc_a2 != CPU_br_predicted_pc_f_a2)));
         assign CPU_valid_mispredicted_a2 = CPU_valid_a2 && CPU_mispredicted_a2;
         assign CPU_misaligned_ex_a2 = (CPU_taken_br_a2 && CPU_br_target_pc_a2[1:0] != 2'b00) || (CPU_is_jalr_a2 && CPU_jalr_target_pc_a2[1:0] != 2'b00);
         assign CPU_valid_misaligned_ex_a2 = CPU_valid_a2 && CPU_misaligned_ex_a2;
         assign CPU_mem_size_a2[1:0] = CPU_funct3_a2[1:0];
         assign CPU_addr_align_mask_a2[1:0] = CPU_mem_size_a2 == 2'b00 ? 2'b00:
                            CPU_mem_size_a2 == 2'b01 ? 2'b01:
                            2'b11;
         assign CPU_misaligned_st_a2 = CPU_is_store_a2 && ((CPU_addr_a2[1:0] & CPU_addr_align_mask_a2) != 2'b00);
         assign CPU_misaligned_ld_a2 = CPU_is_load_a2 && ((CPU_addr_a2[1:0] & CPU_addr_align_mask_a2) != 2'b00);
         assign CPU_misaligned_mem_a2 = CPU_misaligned_ld_a2 || CPU_misaligned_st_a2;
         assign CPU_valid_misaligned_mem_a2 = CPU_valid_a2 && CPU_misaligned_mem_a2;
         assign CPU_take_trap_a2 = CPU_valid_trap_a2 || CPU_valid_misaligned_id_a2 || CPU_valid_misaligned_ex_a2 || CPU_valid_misaligned_mem_a2;
         assign CPU_retires_a2 = CPU_valid_a2 && !CPU_take_trap_a2;

         //ALU Logic
         assign CPU_result_a2[31:0] = (CPU_is_add_a2 || CPU_is_addi_a2) ? CPU_src1_value_fwd_a2 + CPU_src2_or_imm_fwd_a2:
                         (CPU_is_slti_a2 || CPU_is_slt_a2) ? {31'b0, (CPU_src1_value_fwd_a2 < CPU_src2_or_imm_fwd_a2) ^ (CPU_src1_value_fwd_a2[31] != CPU_src2_or_imm_fwd_a2[31])}:
                         (CPU_is_sltiu_a2 || CPU_is_sltu_a2) ? {31'b0, (CPU_src1_value_fwd_a2 < CPU_src2_or_imm_fwd_a2)}:
                         (CPU_is_xori_a2 || CPU_is_xor_a2) ? CPU_src1_value_fwd_a2 ^ CPU_src2_or_imm_fwd_a2:
                         (CPU_is_ori_a2 || CPU_is_or_a2) ? CPU_src1_value_fwd_a2 | CPU_src2_or_imm_fwd_a2:
                         (CPU_is_andi_a2 || CPU_is_and_a2) ? CPU_src1_value_fwd_a2 & CPU_src2_or_imm_fwd_a2:
                         (CPU_is_slli_a2 || CPU_is_sll_a2) ? CPU_src1_value_fwd_a2 << CPU_src2_or_imm_fwd_a2[4:0]:
                         (CPU_is_srli_a2 || CPU_is_srl_a2) ? CPU_src1_value_fwd_a2 >> CPU_src2_or_imm_fwd_a2[4:0]:
                         //bit flip hack to sign extend without $signed from SV
                         (CPU_is_srai_a2 || CPU_is_sra_a2) ? (CPU_src1_value_fwd_a2[31] ? ~(~CPU_src1_value_fwd_a2 >> CPU_src2_or_imm_fwd_a2[4:0]) : CPU_src1_value_fwd_a2 >> CPU_src2_or_imm_fwd_a2[4:0]):
                         CPU_is_sub_a2 ? CPU_src1_value_fwd_a2 - CPU_src2_value_fwd_a2:
                         CPU_is_lui_a2 ? CPU_imm_a2:
                         CPU_is_auipc_a2 ? CPU_pc_a2 + CPU_imm_a2:
                         (CPU_is_jal_a2 || CPU_is_jalr_a2) ? (CPU_pc_a2 + 32'b100):
                         CPU_is_csr_a2 ? CPU_csr_read_data_a2:
                         32'b0;
         assign CPU_addr_a2[31:0] = CPU_src1_value_fwd_a2 + CPU_imm_a2;
         assign CPU_jalr_target_pc_a2[31:0] =  (CPU_src1_value_fwd_a2 + CPU_imm_a2) & ~32'b1;

      //_@3 //MEM
         //Data Memory
         assign CPU_dmem_wr_en_a3 = (CPU_is_sw_a3 || CPU_is_sh_a3 || CPU_is_sb_a3) && CPU_retires_a3;
         assign CPU_dmem_index_a3[18:0] = CPU_addr_a3[20:2];  //19b: covers all 524288 words of the 2MiB range
         assign CPU_dmem_wr_data_a3[31:0] = CPU_funct3_a3 == 3'b010 ? CPU_src2_value_fwd_a3:
                               CPU_funct3_a3 == 3'b001 ? CPU_addr_a3[1] ? {CPU_src2_value_fwd_a3[15:0], CPU_dmem_rd_data_a3[15:0]}:
                                                              {CPU_dmem_rd_data_a3[31:16], CPU_src2_value_fwd_a3[15:0]}:
                               CPU_funct3_a3 == 3'b000 ? (CPU_addr_a3[1:0] == 2'b00 ? {CPU_dmem_rd_data_a3[31:8], CPU_src2_value_fwd_a3[7:0]}:
                                                CPU_addr_a3[1:0] == 2'b01 ? {CPU_dmem_rd_data_a3[31:16], CPU_src2_value_fwd_a3[7:0], CPU_dmem_rd_data_a3[7:0]}:
                                                CPU_addr_a3[1:0] == 2'b10 ? {CPU_dmem_rd_data_a3[31:24], CPU_src2_value_fwd_a3[7:0], CPU_dmem_rd_data_a3[15:0]}:
                                                {CPU_src2_value_fwd_a3[7:0], CPU_dmem_rd_data_a3[23:0]}) :
                               32'b0; //dmem_wr_en low guarenteed so doesn't matter
         /*SV_plus*/
            localparam DMEM_WORDS = 524288;
            logic [31:0] dmem_array [0:DMEM_WORDS-1];
            always_ff @(posedge clk) begin
               if (CPU_dmem_wr_en_a3) begin
                  dmem_array[CPU_dmem_index_a3] <= CPU_dmem_wr_data_a3;
               end
            end
            assign CPU_dmem_rd_data_a3[31:0] = dmem_array[CPU_dmem_index_a3];

         assign CPU_ld_data_a3[31:0] = CPU_funct3_a3 == 3'b001 ? (CPU_addr_a3[1] ? { {16{CPU_dmem_rd_data_a3[31]}}, CPU_dmem_rd_data_a3[31:16]}:
                                                       { {16{CPU_dmem_rd_data_a3[15]}}, CPU_dmem_rd_data_a3[15:0]}) :
                          CPU_funct3_a3 == 3'b101 ? (CPU_addr_a3[1] ? {16'b0, CPU_dmem_rd_data_a3[31:16]}:
                                                       {16'b0, CPU_dmem_rd_data_a3[15:0]}) :
                          CPU_funct3_a3 == 3'b000 ? (CPU_addr_a3[1:0] == 2'b00 ? { {24{CPU_dmem_rd_data_a3[7]}}, CPU_dmem_rd_data_a3[7:0]}:
                                            CPU_addr_a3[1:0] == 2'b01 ? { {24{CPU_dmem_rd_data_a3[15]}}, CPU_dmem_rd_data_a3[15:8]}:
                                            CPU_addr_a3[1:0] == 2'b10 ? { {24{CPU_dmem_rd_data_a3[23]}}, CPU_dmem_rd_data_a3[23:16]}:
                                            { {24{CPU_dmem_rd_data_a3[31]}}, CPU_dmem_rd_data_a3[31:24]}) :
                          CPU_funct3_a3 == 3'b100 ? (CPU_addr_a3[1:0] == 2'b00 ? {24'b0, CPU_dmem_rd_data_a3[7:0]}:
                                            CPU_addr_a3[1:0] == 2'b01 ? {24'b0, CPU_dmem_rd_data_a3[15:8]}:
                                            CPU_addr_a3[1:0] == 2'b10 ? {24'b0, CPU_dmem_rd_data_a3[23:16]}:
                                            {24'b0, CPU_dmem_rd_data_a3[31:24]}) :
                          CPU_dmem_rd_data_a3; //saves gates by aliasing funct3 instead of is_*, order lh, lhu, lb, lbu, lw
      //_@4 //WB
         assign CPU_rf_wr_data_a4[31:0] = (CPU_is_lw_a4 || CPU_is_lh_a4 || CPU_is_lhu_a4 || CPU_is_lb_a4 || CPU_is_lbu_a4) ? CPU_ld_data_a4:
                             CPU_result_a4;
//_\SV
   endmodule


